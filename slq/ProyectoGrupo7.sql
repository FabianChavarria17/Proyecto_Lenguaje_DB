--Script del proyecto del grupo 7
--Sistema de ferreteria 

SET DEFINE OFF

--Creacion de dueño de tablas y accesos 

CREATE USER FERRE_OWNER IDENTIFIED BY "Owner_Ferre2026"
    DEFAULT TABLESPACE USERS
    TEMPORARY TABLESPACE TEMP
    QUOTA UNLIMITED ON USERS;

GRANT CREATE SESSION   TO FERRE_OWNER;
GRANT CREATE TABLE     TO FERRE_OWNER;
GRANT CREATE VIEW      TO FERRE_OWNER;
GRANT CREATE SEQUENCE  TO FERRE_OWNER;
GRANT CREATE PROCEDURE TO FERRE_OWNER;
GRANT CREATE TRIGGER   TO FERRE_OWNER;

--Creacion de roles
CREATE ROLE ROL_DESARROLLADOR;
CREATE ROLE ROL_USUARIO_FINAL;
GRANT CREATE SESSION TO ROL_DESARROLLADOR;
GRANT CREATE SESSION TO ROL_USUARIO_FINAL;


--User Dev
CREATE USER FERRE_DEV IDENTIFIED BY "Dev_Ferre2026"
    DEFAULT TABLESPACE USERS
    TEMPORARY TABLESPACE TEMP;
GRANT ROL_DESARROLLADOR TO FERRE_DEV;

--Final user
CREATE USER FERRE_APP IDENTIFIED BY "App_Ferre2026"
    DEFAULT TABLESPACE USERS
    TEMPORARY TABLESPACE TEMP;
GRANT ROL_USUARIO_FINAL TO FERRE_APP;

--Verificacion 
SELECT username FROM dba_users WHERE username LIKE 'FERRE%' ORDER BY 1;
SELECT grantee, granted_role FROM dba_role_privs WHERE grantee LIKE 'FERRE%' ORDER BY 1;


